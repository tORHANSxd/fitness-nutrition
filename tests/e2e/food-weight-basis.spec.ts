import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { manualGoal } from "./ui-helpers";

test("raw/cooked weight input, bounds, save and reload @a11y", async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  const fixture = "http://127.0.0.1:45432";
  await request.post(`${fixture}/fixture/reset`);
  const foodId = "60000000-0000-4000-8000-000000000001";
  const foodName = "生熟换算测试米";
  await request.post(`${fixture}/rest/v1/foods`, { data: { id: foodId, user_id: "50000000-0000-4000-8000-000000000001", name: foodName, category: "主食", weight_basis: "raw", cooked_raw_ratio: 2.5, carbs_per_100g: 80, protein_per_100g: 8, fat_per_100g: 1, kcal_per_100g: 361, source: "user", archived_at: null } });
  const state = async () => (await request.get(`${fixture}/fixture/state`)).json();
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill("browser-fixture@example.test");
  await page.getByLabel("密码", { exact: true }).fill("synthetic-ui-only");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/(overview|today)/);
  await page.goto("/today");
  await manualGoal(page);
  await page.goto("/today");
  await page.getByRole("button", { name: "添加食物", exact: true }).first().click();
  const picker = page.getByRole("dialog");
  await picker.getByLabel("搜索食物", { exact: true }).fill(foodName);
  await picker.getByRole("button", { name: new RegExp(`^${foodName} `) }).click();
  const row = page.locator(".food-entry-row").filter({ has: page.getByRole("button", { name: `更换${foodName}`, exact: true }) });
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("100");
  await expect(row.getByLabel(`${foodName}生熟重量`)).toHaveText("生重 100 g · 熟重约 250 g");
  await row.locator("summary").filter({ hasText: "分量范围与生熟换算" }).click();
  await row.getByLabel(`${foodName}最小克重`).fill("80");
  await row.getByLabel(`${foodName}最大克重`).fill("120");
  await row.getByLabel(`${foodName}计算标准`).selectOption("cooked");
  await expect(row.getByLabel(`${foodName}克重`, { exact: true })).toHaveValue("250");
  await expect(row.getByLabel(`${foodName}最小克重`)).toHaveValue("200");
  await expect(row.getByLabel(`${foodName}最大克重`)).toHaveValue("300");
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("100");
  await expect(row.getByLabel(`${foodName}生熟重量`)).toHaveText("生重约 40 g · 熟重 100 g");
  await expect(row).toContainText("碳 32 · 蛋 3.2 · 脂 0.4 g");
  await page.getByRole("button", { name: "保存计划", exact: true }).click();
  await expect.poll(async () => (await state()).daily_plans.length).toBe(1);
  const saved = (await state()).daily_plans[0];
  const entry = saved.meals.flatMap((meal: { entries: Record<string, unknown>[] }) => meal.entries).find((item: Record<string, unknown>) => item.foodId === foodId);
  expect(entry).toMatchObject({ grams: 40, minGrams: 80, maxGrams: 120, inputWeightBasis: "cooked", locked: true });
  await page.reload();
  await expect(row.getByLabel(`${foodName}克重`, { exact: true })).toHaveValue("100");
  await expect(row.getByLabel(`${foodName}计算标准`)).toHaveValue("cooked");
  await row.screenshot({ path: testInfo.outputPath("food-weight-basis.png") });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= innerWidth + 1)).toBe(true);
  expect((await new AxeBuilder({ page }).analyze()).violations.filter((item) => ["critical", "serious"].includes(item.impact ?? ""))).toEqual([]);
  expect(errors).toEqual([]);
});
