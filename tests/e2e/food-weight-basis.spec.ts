import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { manualGoal } from "./ui-helpers";

test("raw/cooked weight input, bounds, save and reload @a11y", async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  const fixture = "http://127.0.0.1:45432";
  await request.post(`${fixture}/fixture/reset`);
  const foodId = "60000000-0000-4000-8000-000000000001";
  const foodName = "生熟换算测试米";
  await request.post(`${fixture}/rest/v1/foods`, { data: { id: foodId, user_id: "50000000-0000-4000-8000-000000000001", name: foodName, category: "主食", weight_basis: "raw", cooked_raw_ratio: 2.5, carbs_per_100g: 80, protein_per_100g: 8, fat_per_100g: 1, kcal_per_100g: 361, source: "user", archived_at: null } });
  const state = async () => (await request.get(`${fixture}/fixture/state`)).json();
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill("browser-fixture@example.test");
  await page.getByLabel("密码", { exact: true }).fill("synthetic-ui-only");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/(overview|today)/);
  await page.goto("/today");
  await manualGoal(page);
  await page.goto("/today");
  await page.getByRole("button", { name: "添加食物", exact: true }).first().click();
  const picker = page.getByRole("dialog");
  await picker.getByLabel("搜索食物", { exact: true }).fill(foodName);
  await picker.getByRole("button", { name: new RegExp(`^${foodName} `) }).click();
  const row = page.locator(".food-entry-row").filter({ has: page.getByRole("button", { name: `更换${foodName}`, exact: true }) });
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("100");
  await expect(row.getByLabel(`${foodName}生熟重量`)).toHaveText("生重 100 g · 熟重约 250 g");
  await row.locator("summary").filter({ hasText: "分量范围与生熟换算" }).click();
  await row.getByLabel(`${foodName}最小克重`).fill("80");
  await row.getByLabel(`${foodName}最大克重`).fill("120");
  await row.getByLabel(`${foodName}计算标准`).selectOption("cooked");
  await expect(row.getByLabel(`${foodName}克重`, { exact: true })).toHaveValue("250");
  await expect(row.getByLabel(`${foodName}最小克重`)).toHaveValue("200");
  await expect(row.getByLabel(`${foodName}最大克重`)).toHaveValue("300");
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("100");
  await expect(row.getByLabel(`${foodName}生熟重量`)).toHaveText("生重约 40 g · 熟重 100 g");
  await expect(row).toContainText("碳 32 · 蛋 3.2 · 脂 0.4 g");
  await page.getByRole("button", { name: "保存计划", exact: true }).click();
  await expect.poll(async () => (await state()).daily_plans.length).toBe(1);
  const saved = (await state()).daily_plans[0];
  const entry = saved.meals.flatMap((meal: { entries: Record<string, unknown>[] }) => meal.entries).find((item: Record<string, unknown>) => item.foodId === foodId);
  expect(entry).toMatchObject({ grams: 40, minGrams: 80, maxGrams: 120, inputWeightBasis: "cooked", locked: false });
  await page.reload();
  await expect(row.getByLabel(`${foodName}克重`, { exact: true })).toHaveValue("100");
  await expect(row.getByLabel(`${foodName}计算标准`)).toHaveValue("cooked");
  await row.screenshot({ path: testInfo.outputPath("food-weight-basis.png") });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= innerWidth + 1)).toBe(true);
  expect((await new AxeBuilder({ page }).analyze()).violations.filter((item) => ["critical", "serious"].includes(item.impact ?? ""))).toEqual([]);
  expect(errors).toEqual([]);
});

test("supplements default to unlocked; edits, recommendations and explicit locks survive reload", async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  const fixture = "http://127.0.0.1:45432";
  await request.post(`${fixture}/fixture/reset`);
  const foodId = "60000000-0000-4000-8000-000000000002";
  const foodName = "合成蛋白粉";
  await request.post(`${fixture}/rest/v1/foods`, { data: { id: foodId, user_id: "50000000-0000-4000-8000-000000000001", name: foodName, category: "补剂", weight_basis: "none", cooked_raw_ratio: null, carbs_per_100g: 10, protein_per_100g: 90, fat_per_100g: 0, kcal_per_100g: 400, source: "user", portion_policy: "fixed_dose", archived_at: null } });
  const state = async () => (await request.get(`${fixture}/fixture/state`)).json();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill("browser-fixture@example.test");
  await page.getByLabel("密码", { exact: true }).fill("synthetic-ui-only");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/(overview|today)/);
  await page.goto("/resources?tab=foods");
  await page.getByLabel("搜索食物", { exact: true }).fill(foodName);
  await page.getByRole("button", { name: `编辑${foodName}`, exact: true }).click();
  const editor = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: "编辑食物", exact: true }) });
  const fixedDose = editor.getByRole("checkbox", { name: "固定剂量，不参与自动配餐", exact: true });
  await expect(fixedDose).toBeEnabled();
  await fixedDose.uncheck();
  await editor.getByRole("button", { name: "保存食物", exact: true }).click();
  await expect.poll(async () => (await state()).foods[0].portion_policy).toBe("food");
  await manualGoal(page);
  await page.goto("/today");
  await page.getByRole("button", { name: "添加食物", exact: true }).first().click();
  const picker = page.getByRole("dialog", { name: "添加食物", exact: true });
  await picker.getByLabel("搜索食物", { exact: true }).fill(foodName);
  await picker.getByRole("button", { name: new RegExp(`^${foodName} `) }).click();
  const row = page.locator(".food-entry-row").filter({ has: page.getByRole("button", { name: `更换${foodName}`, exact: true }) });
  const lock = row.getByRole("button", { name: `锁定${foodName}分量`, exact: true });
  await expect(lock).toBeEnabled();
  await expect(lock).toHaveAttribute("aria-pressed", "false");
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("10");
  await expect(lock).toHaveAttribute("aria-pressed", "false");
  await row.locator("summary").filter({ hasText: "分量范围与生熟换算" }).click();
  await row.getByLabel(`${foodName}最大克重`).fill("40");
  await page.getByRole("button", { name: "调整分量", exact: true }).click();
  await page.getByRole("button", { name: "确认调整", exact: true }).click();
  const amount = Number(await row.getByLabel(`${foodName}克重`, { exact: true }).inputValue());
  expect(amount).toBeGreaterThan(10);
  expect(amount).toBeLessThanOrEqual(40);
  await lock.click();
  await row.getByLabel(`${foodName}克重`, { exact: true }).fill("12");
  await expect(lock).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("button", { name: "调整分量", exact: true })).toBeDisabled();
  await lock.click();
  await page.getByRole("button", { name: "添加食物", exact: true }).first().click();
  await picker.getByLabel("搜索食物", { exact: true }).fill("肌酸");
  await picker.getByRole("button", { name: /^肌酸 / }).click();
  const creatineLock = page.getByRole("button", { name: "锁定肌酸分量", exact: true });
  await expect(creatineLock).toBeEnabled();
  await expect(creatineLock).toHaveAttribute("aria-pressed", "false");
  await page.getByRole("button", { name: "保存计划", exact: true }).click();
  await expect.poll(async () => (await state()).daily_plans.length).toBe(1);
  const entries = (await state()).daily_plans[0].meals.flatMap((meal: { entries: Record<string, unknown>[] }) => meal.entries);
  expect(entries.find((entry: Record<string, unknown>) => entry.foodId === foodId)).toMatchObject({ grams: 12, maxGrams: 40, locked: false, foodSnapshot: { version: 2, portionPolicy: "food" } });
  expect(entries.every((entry: { locked: boolean }) => !entry.locked)).toBe(true);
  await page.reload();
  await expect(lock).toHaveAttribute("aria-pressed", "false");
  await expect(creatineLock).toHaveAttribute("aria-pressed", "false");
  await expect(row.getByLabel(`${foodName}克重`, { exact: true })).toHaveValue("12");
  await row.screenshot({ path: testInfo.outputPath("supplement-unlocked.png") });
  expect(await page.locator("body").evaluate(body => body.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
