import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { syntheticStandard } from "../fixtures/nutritionStandardFixture";

test("个人标准导入、恢复门禁、确认及重新加载 @a11y", async ({ page, request }, testInfo) => {
  await request.post("http://127.0.0.1:45432/fixture/reset");
  await page.goto("/login");
  await page.getByLabel("邮箱", { exact: true }).fill("browser-fixture@example.test");
  await page.getByLabel("密码", { exact: true }).fill("synthetic-ui-only");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL(/\/(overview|today)/);
  await page.goto("/goals");
  const panel = page.getByRole("region", { name: "自动营养目标", exact: true });
  await panel.getByLabel("导入个人标准 JSON").setInputFiles({ name: "synthetic-standard.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(syntheticStandard)) });
  await expect(panel).toContainText("草案已载入，尚未生效");
  const state = async () => (await request.get("http://127.0.0.1:45432/fixture/state")).json();
  expect((await state()).user_plan_protocols).toHaveLength(0);
  expect((await state()).nutrition_standard_proposals).toHaveLength(1);
  await expect(panel.getByLabel(/预览7天训练/)).toBeDisabled();
  await expect(panel.getByTestId("candidate-carbs")).toHaveText("223.8 g");
  await panel.getByLabel(/我已成年/).check();
  await panel.getByRole("combobox", { name: "恢复状态", exact: true }).selectOption("concern");
  await expect(panel.getByRole("button", { name: "预览调整" })).toBeDisabled();
  await panel.getByRole("combobox", { name: "恢复状态", exact: true }).selectOption("stable");
  await panel.getByRole("button", { name: "预览调整" }).click();
  await expect(panel.getByLabel("自动目标应用预览")).toContainText("下午加餐 16:00—16:30");
  await page.screenshot({ path: testInfo.outputPath("standard-preview.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ["critical", "serious"].includes(v.impact ?? ""))).toEqual([]);
  expect(await page.locator("body").evaluate(b => b.scrollWidth <= innerWidth + 1)).toBe(true);
  await panel.getByRole("button", { name: "确认目标" }).click();
  await expect(panel.getByText("查看计算依据", { exact: true })).toBeVisible();
  const protocol = (await state()).user_plan_protocols[0].config;
  expect(protocol.schemaVersion).toBe(3);
  expect(protocol.reviewMode).toBe("personal_standard_v1");
  expect(protocol.nutritionStrategy).toEqual({ version: 1, mode: "fixed_daily" });
  expect(protocol.preTrainingNoIntakeMinutes).toBe(0);
  expect(protocol.dailyTarget).toEqual(syntheticStandard.dailyTarget);
  await page.reload();
  await expect(panel.getByText("查看计算依据", { exact: true })).toBeVisible();
  expect((await state()).user_plan_protocols).toHaveLength(1);
});
