import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { login } from "./ui-helpers";
const fixture = "http://127.0.0.1:45432";
test("first visit, real meal actions, lock persistence, replay and keyboard access", async ({ page, request }, info) => {
  await request.post(`${fixture}/fixture/reset`, { data: { preferences: { tutorial_seen_version: 0 } } });
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await login(page);
  const catalog = page.getByRole("dialog", { name: "跟着做一遍" });
  await expect(catalog).toBeVisible();
  await page.screenshot({ path: info.outputPath("tutorial-welcome.png") });
  await catalog.getByRole("button", { name: /安排第一餐/ }).click();
  const guide = page.getByRole("region", { name: "操作引导" });
  await expect(guide.getByRole("button", { name: "继续", exact: true })).toBeDisabled();
  await page.locator('[data-tour="meal-add"]').click();
  const picker = page.getByRole("dialog", { name: "添加食物", exact: true });
  await picker.getByRole("textbox", { name: "搜索食物", exact: true }).fill("燕麦片");
  await expect(picker.getByText("燕麦片", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("tutorial-picker.png") });
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ["serious","critical"].includes(v.impact ?? ""))).toEqual([]);
  await picker.getByText("燕麦片", { exact: true }).click();
  await expect(guide.getByRole("button", { name: "继续", exact: true })).toBeEnabled();
  await guide.getByRole("button", { name: "继续", exact: true }).click();
  await page.getByLabel("燕麦片克重", { exact: true }).fill("80");
  await guide.getByRole("heading").click();
  await guide.getByRole("button", { name: "继续", exact: true }).click();
  const lock = page.getByRole("button", { name: "锁定燕麦片分量", exact: true });
  await expect(lock).toHaveAttribute("aria-pressed", "true");
  await lock.click();
  await expect(lock).toHaveAttribute("aria-pressed", "false");
  await guide.getByRole("button", { name: "继续", exact: true }).click();
  await page.getByRole("button", { name: "锁定整餐", exact: true }).click();
  await expect(lock).toBeDisabled();
  await page.screenshot({ path: info.outputPath("tutorial-locks.png") });
  await guide.getByRole("button", { name: "继续", exact: true }).click();
  await page.getByRole("button", { name: "保存计划", exact: true }).click();
  await expect(guide.getByRole("button", { name: "完成这一段", exact: true })).toBeEnabled();
  await guide.getByRole("button", { name: "完成这一段", exact: true }).click();
  await page.getByRole("button", { name: "开始自己使用", exact: true }).click();
  await expect.poll(async () => (await (await request.get(`${fixture}/fixture/state`)).json()).profiles[0].tutorial_seen_version).toBe(1);
  await page.reload();
  await expect(page.getByRole("button", { name: "锁定整餐", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByLabel("燕麦片克重", { exact: true })).toHaveValue("80");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "查看教程", exact: true }).filter({ visible: true }).click();
  await expect(catalog).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(catalog).toHaveCount(0);
  expect(await page.locator("body").evaluate(el => el.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
