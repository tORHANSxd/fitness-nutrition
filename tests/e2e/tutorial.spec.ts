test("a failed real save cannot complete a step; skipping is reported as ending", async ({ page, request }) => {
  await request.post(`${fixture}/fixture/reset`);
  await login(page);
  await page.getByRole("button", { name: "查看教程", exact: true }).filter({ visible: true }).click();
  await page.getByRole("button", { name: /安排第一餐/ }).click();
  const guide = page.getByRole("region", { name: "操作引导" });
  for (let i = 0; i < 4; i++) await guide.getByRole("button", { name: "跳过这一步", exact: true }).click();
  await page.route("**/rest/v1/daily_plans**", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "synthetic save failure" }) }));
  await page.getByRole("button", { name: "保存计划", exact: true }).click();
  await expect(page.getByText("保存失败。", { exact: true })).toBeVisible();
  await expect(guide.getByRole("button", { name: "完成这一段", exact: true })).toBeDisabled();
  await guide.getByRole("button", { name: "跳过这一步", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "这一段已结束" })).toBeVisible();
  const state = await (await request.get(`${fixture}/fixture/state`)).json();
  expect(state.daily_plans).toHaveLength(0);
});
